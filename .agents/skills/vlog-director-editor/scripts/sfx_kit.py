"""Synthesize the small SFX kit that every style draws its default sounds from.

The sounds are generated from noise and tones, so there are no licence limits.
Writes 48 kHz stereo WAVs plus SOURCES.md into <project>/05_Shared_Assets/sfx/synth/.

Usage:
  python sfx_kit.py --root <project>
"""
import argparse
import subprocess
from pathlib import Path

import numpy as np
from scipy.signal import butter, sosfilt

SR = 48000
RNG = np.random.default_rng(7)


def t(sec):
    return np.arange(int(sec * SR)) / SR


def band(x, lo, hi):
    return sosfilt(butter(4, [lo, hi], btype="band", fs=SR, output="sos"), x)


def low(x, hz):
    return sosfilt(butter(4, hz, btype="low", fs=SR, output="sos"), x)


def env(n, attack, decay):
    a = int(attack * SR)
    e = np.exp(-np.arange(n) / (decay * SR))
    if a:
        e[:a] *= np.linspace(0, 1, a)
    return e


def crackle(n, rate, decay=0.004):
    imp = (RNG.random(n) < rate / SR) * RNG.uniform(.3, 1, n)
    kernel = np.exp(-np.arange(int(decay * SR)) / (decay * SR / 4))
    return np.convolve(imp, kernel)[:n]


def thump(freq, sec, drop=0.5):
    tt = t(sec)
    f = freq * (1 + drop * np.exp(-tt * 40))
    return np.sin(2 * np.pi * np.cumsum(f) / SR) * env(len(tt), .001, sec / 4)


def noise(sec):
    return RNG.standard_normal(int(sec * SR))


def sounds():
    out = {}
    n = noise(.09)
    out["paper_slap"] = band(n, 900, 7000) * env(len(n), .001, .018) + .6 * np.pad(thump(140, .06), (0, len(n) - int(.06 * SR)))
    n = noise(.55)
    out["paper_tear"] = band(n, 1200, 9000) * (.25 + crackle(len(n), 260)) * np.hanning(len(n)) ** .3
    n = noise(.35)
    out["tape"] = band(n, 2500, 11000) * (.15 + crackle(len(n), 420)) * np.linspace(.4, 1, len(n)) * env(len(n), .01, .25)
    s = thump(70, .25, .8)
    click = band(noise(.25), 600, 5000) * env(int(.25 * SR), .0005, .01)
    tail = low(noise(.25), 1800) * env(int(.25 * SR), .002, .06) * .25
    out["stamp"] = s + .7 * click + tail
    tt = t(.12)
    out["pop"] = np.sin(2 * np.pi * np.cumsum(700 * np.exp(-tt * 18) + 220) / SR) * env(len(tt), .001, .03)
    tt = t(.65)
    sweep = np.sin(2 * np.pi * np.cumsum(np.linspace(1400, 300, len(tt))) / SR)
    stutter = (np.sin(2 * np.pi * 22 * tt) > -.2).astype(float)
    out["rewind"] = (.5 * sweep + .35 * band(noise(.65), 1500, 6000)) * stutter * np.hanning(len(tt)) ** .4
    a = band(noise(.03), 1500, 9000) * env(int(.03 * SR), .0003, .004)
    gap = np.zeros(int(.07 * SR))
    out["shutter"] = np.concatenate([a, gap, a * .8, np.zeros(int(.05 * SR))])
    n = noise(.6)
    stroke = (np.sin(2 * np.pi * 7 * t(.6)) * .5 + .5) ** 2
    out["pen"] = band(n, 3000, 9000) * stroke * .5 * env(len(n), .02, .4)
    n = noise(.3)
    out["hit"] = thump(55, .3, 1.2) + .5 * band(n, 300, 4000) * env(len(n), .0005, .03)
    tt = t(.18)
    out["boing"] = np.sin(2 * np.pi * np.cumsum(180 + 140 * np.sin(2 * np.pi * 14 * tt) * np.exp(-tt * 9) + 260 * np.exp(-tt * 20)) / SR) * env(len(tt), .002, .08)
    tt = t(.9)
    bell = sum(np.sin(2 * np.pi * f * tt) * g for f, g in ((1568, 1), (3136, .35), (4700, .15)))
    out["ding"] = bell * env(len(tt), .001, .25)
    n = noise(.45)
    sweep = np.linspace(0, 1, len(n))
    out["whoosh"] = band(n, 500, 5000) * np.sin(np.pi * sweep) ** 2
    out["boom"] = thump(48, .6, 1.5) + .6 * low(noise(.6), 900) * env(int(.6 * SR), .001, .12)
    tt = t(1.6)
    chime = sum(np.sin(2 * np.pi * f * tt) * g for f, g in ((1046.5, 1), (1318.5, .7), (1568, .5), (2093, .25)))
    out["chime"] = chime * env(len(tt), .02, .6)
    return out


def write(path, x):
    x = x / (np.abs(x).max() + 1e-9) * 10 ** (-1 / 20)
    stereo = np.stack([x, x], axis=1).astype(np.float32)
    subprocess.run(["ffmpeg", "-y", "-v", "error", "-f", "f32le", "-ar", str(SR), "-ac", "2", "-i", "pipe:0",
                    "-c:a", "pcm_s16le", str(path)], input=stereo.tobytes(), check=True)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", required=True, type=Path)
    a = ap.parse_args()
    out = a.root / "05_Shared_Assets" / "sfx" / "synth"
    out.mkdir(parents=True, exist_ok=True)
    kit = sounds()
    for name, x in kit.items():
        write(out / f"{name}.wav", x)
    (out / "SOURCES.md").write_text(
        "# Synth SFX\n\nGenerated by `.agents/skills/vlog-director-editor/scripts/sfx_kit.py` "
        "from noise and tones. No third-party audio, no licence restrictions.\n\n"
        + "\n".join(f"- `{k}.wav`" for k in kit) + "\n", encoding="utf-8")
    print(f"wrote {len(kit)} sounds to {out}")


if __name__ == "__main__":
    main()
